"""Override layers: the street-level classifications that sit on top of the Wikidata/theme reconciliation.

Instead of one big `manual_overrides.json` (where a rule silently replaced earlier entries), overrides live in layers applied in a fixed order;
a later layer wins on the same street, and each layer can be regenerated alone:

  legacy_hand     29k hand/LLM classifications made by the archived wave scripts; frozen, irreplaceable   (config.KNOWLEDGE/overrides/legacy_hand.json)
  <rule layers>   one file per rule in PRECEDENCE order, regenerated by `rules/run.py --apply RULE`        (config.ENRICHED/overrides/<rule>.json)

`corrections` (reviewed street-level decisions from corrections.json) is the last layer, so it overrides everything. A layer file is
{"layer": name, "overrides": [ {gemeente, street, category, subcategory, entity_label, entity_description, confidence, source, source_url, notes}, ... ]}.

  python src/overrides.py --migrate   split the old manual_overrides.json into layers (one-off; checks the merged result is identical)
  python src/overrides.py --status    layer sizes and the streets they decide
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import config

LEGACY = "legacy_hand"
# Layer order = dependency order, and later wins on the same street. Rules that refine another rule's output come after it (species turns the
# generic plant/animal descriptions that vocabulary and the hand lists left into the actual species; label_cleanup repairs labels the classifiers
# wrote; the audits check the classifiers' result; the resolver and OSM rules work on what is still unresolved or verify it). Reviewed
# corrections are last. rules/run.py imports this list.
PRECEDENCE = ["vocabulary", "titles", "directional_road", "species", "label_cleanup", "bare_surname", "same_name_harmonise", "person_consensus",
              "theme_forced_name_fit", "wikidata_place_review", "name_resolver", "osm_places", "osm_etymology", "corrections"]
LAYER_ORDER = [LEGACY] + PRECEDENCE
FIELDS = ("category", "subcategory", "entity_label", "entity_description", "confidence", "source", "source_url", "notes")


def layer_path(name: str) -> Path:
    if name == LEGACY:
        return config.KNOWLEDGE / "overrides" / f"{name}.json"
    return config.ENRICHED / "overrides" / f"{name}.json"


def load_layer(name: str) -> list[dict]:
    p = layer_path(name)
    return json.loads(p.read_text())["overrides"] if p.exists() else []


def write_layer(name: str, entries: list[dict]) -> None:
    p = layer_path(name)
    p.parent.mkdir(parents=True, exist_ok=True)
    entries = sorted(entries, key=lambda o: (o["gemeente"], o["street"]))
    p.write_text(json.dumps({"layer": name, "overrides": entries}, indent=1, ensure_ascii=False))


def merged(exclude=(), upto: str | None = None) -> dict:
    """{(gemeente, street): entry}: layers applied in LAYER_ORDER, later wins. `exclude` skips named layers; `upto` stops before that layer
    (what a rule sees when it computes its own proposals: everything that ranks below it, nothing of itself or above)."""
    out = {}
    for name in LAYER_ORDER:
        if name == upto:
            break
        if name in exclude:
            continue
        for o in load_layer(name):
            out[(o["gemeente"], o["street"])] = o
    return out


def diff(old: list[dict], new: list[dict]) -> dict:
    """How a regenerated layer differs from the one on disk."""
    key = lambda o: (o["gemeente"], o["street"])
    value = lambda o: tuple(o.get(f) for f in FIELDS)
    a, b = {key(o): value(o) for o in old}, {key(o): value(o) for o in new}
    return {"added": len(b.keys() - a.keys()), "removed": len(a.keys() - b.keys()), "changed": sum(1 for k in a.keys() & b.keys() if a[k] != b[k]),
            "unchanged": sum(1 for k in a.keys() & b.keys() if a[k] == b[k])}


def migrate() -> None:
    old_path = config.ENRICHED / "manual_overrides.json"
    old = json.loads(old_path.read_text())["overrides"]
    by_layer: dict[str, list] = {}
    for o in old:
        layer = o.get("rule") or LEGACY
        if layer not in LAYER_ORDER:
            raise SystemExit(f"override for {o['street']} comes from unknown rule '{layer}'")
        by_layer.setdefault(layer, []).append({k: v for k, v in o.items() if k != "rule"})
    expected = {(o["gemeente"], o["street"]): {k: v for k, v in o.items() if k != "rule"} for o in old}
    assert len(expected) == len(old), "duplicate (gemeente, street) in the old file"
    for name, entries in by_layer.items():
        write_layer(name, entries)
    got = merged()
    assert got.keys() == expected.keys() and all(got[k] == expected[k] for k in expected), "merged layers differ from the old file"
    print(f"split {len(old)} overrides into {len(by_layer)} layers: " + ", ".join(f"{n} {len(by_layer[n])}" for n in LAYER_ORDER if n in by_layer))


def status() -> None:
    owner = {}
    for name in LAYER_ORDER:
        for o in load_layer(name):
            owner[(o["gemeente"], o["street"])] = name
    import collections
    decided = collections.Counter(owner.values())
    for name in LAYER_ORDER:
        n = len(load_layer(name))
        print(f"{name:24}{n:7} entries{decided.get(name, 0):7} decide a street  ({config.rel(layer_path(name))})")


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--migrate", action="store_true")
    ap.add_argument("--status", action="store_true")
    a = ap.parse_args()
    migrate() if a.migrate else status()
