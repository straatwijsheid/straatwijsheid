"""Override layers: the street-level classifications that sit on top of the Wikidata/theme reconciliation.

Instead of one big `manual_overrides.json` (where a rule silently replaced earlier entries), overrides live in layers applied in a fixed order;
a later layer wins on the same street, and each layer can be regenerated alone:

  legacy_hand     29k hand/LLM classifications made by the archived wave scripts; frozen, irreplaceable   (knowledge/gemeenten/<province>/<gemeente>/overrides/legacy_hand.json)
  <rule layers>   one file per rule in PRECEDENCE order, regenerated by `rules/run.py --apply RULE`        (same folder, <rule>.json)

`corrections` (reviewed street-level decisions from corrections.json) is the last layer, so it overrides everything. A layer file is
{"layer": name, "overrides": [ {gemeente, street, category, subcategory, entity_label, entity_description, confidence, source, source_url, notes}, ... ]}.

  python src/overrides.py --status    layer sizes and the streets they decide
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import config
import knowledge

LEGACY = "legacy_hand"
# Layer order = dependency order, and later wins on the same street. Rules that refine another rule's output come after it (species turns the
# generic plant/animal descriptions that vocabulary and the hand lists left into the actual species; label_cleanup repairs labels the classifiers
# wrote; the audits check the classifiers' result; the resolver and OSM rules work on what is still unresolved or verify it). Reviewed
# corrections are last. rules/run.py imports this list.
PRECEDENCE = ["vocabulary", "titles", "directional_road", "species", "label_cleanup", "bare_surname", "same_name_harmonise", "person_consensus",
              "theme_forced_name_fit", "wikidata_place_review", "name_resolver", "osm_places", "osm_etymology", "corrections"]
LAYER_ORDER = [LEGACY] + PRECEDENCE
FIELDS = ("category", "subcategory", "entity_label", "entity_description", "confidence", "source", "source_url", "notes")


def layer_path(name: str, gemeente_code: str) -> Path:
    """One file per layer per gemeente: <knowledge>/gemeenten/<province>/<gemeente>/overrides/<layer>.json (see knowledge.py)."""
    return knowledge.gemeente_dir(gemeente_code) / "overrides" / f"{name}.json"


def layer_files(name: str) -> list[Path]:
    return [p for d in knowledge.shard_dirs() if (p := d / "overrides" / f"{name}.json").exists()]


def load_layer(name: str) -> list[dict]:
    """The entries of a layer, each with the `gemeente_code` of the shard it was read from (the key; the stored `gemeente` name is for display)."""
    out = []
    for p in layer_files(name):
        code = knowledge.code_of_shard(p.parent.parent)
        out.extend({**o, "gemeente_code": code} for o in json.loads(p.read_text())["overrides"])
    return out


def write_layer(name: str, entries: list[dict]) -> None:
    """Write the layer sharded by gemeente; a gemeente that no longer has entries loses its file."""
    entries = sorted(entries, key=lambda o: (o["gemeente_code"], o["street"]))
    by: dict[str, list] = {}
    for o in entries:
        by.setdefault(o["gemeente_code"], []).append({k: v for k, v in o.items() if k != "gemeente_code"})   # the code is the shard, not stored per entry
    keep = {layer_path(name, g) for g in by}
    for p in layer_files(name):
        if p not in keep:
            p.unlink()
    for g, items in by.items():
        knowledge.write_json(layer_path(name, g), {"layer": name, "overrides": items})


def merged(exclude=(), upto: str | None = None) -> dict:
    """{(gemeente_code, street): entry}: layers applied in LAYER_ORDER, later wins. `exclude` skips named layers; `upto` stops before that layer
    (what a rule sees when it computes its own proposals: everything that ranks below it, nothing of itself or above)."""
    out = {}
    for name in LAYER_ORDER:
        if name == upto:
            break
        if name in exclude:
            continue
        for o in load_layer(name):
            out[(o["gemeente_code"], o["street"])] = o
    return out


def diff(old: list[dict], new: list[dict]) -> dict:
    """How a regenerated layer differs from the one on disk."""
    key = lambda o: (o["gemeente_code"], o["street"])
    value = lambda o: tuple(o.get(f) for f in FIELDS)
    a, b = {key(o): value(o) for o in old}, {key(o): value(o) for o in new}
    return {"added": len(b.keys() - a.keys()), "removed": len(a.keys() - b.keys()), "changed": sum(1 for k in a.keys() & b.keys() if a[k] != b[k]),
            "unchanged": sum(1 for k in a.keys() & b.keys() if a[k] == b[k])}


def status() -> None:
    owner = {}
    for name in LAYER_ORDER:
        for o in load_layer(name):
            owner[(o["gemeente_code"], o["street"])] = name
    import collections
    decided = collections.Counter(owner.values())
    for name in LAYER_ORDER:
        n = len(load_layer(name))
        print(f"{name:24}{n:7} entries{decided.get(name, 0):7} decide a street  ({len(layer_files(name))} gemeenten)")


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--status", action="store_true")
    ap.parse_args()
    status()
