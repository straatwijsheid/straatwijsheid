"""Wikidata-side failures found while using OSM/Wikidata as evidence, written to WIKIDATA_FIXES.md (so they can be fixed on Wikidata).

These are NOT OpenStreetMap errors (see OSM_FIXES.md): the street's own Wikidata item has a 'named after' (P138) statement that is
wrong, or points at an item whose English label/description does not describe what the street is named after.

  python src/wikidata_fixes.py
"""
from __future__ import annotations

import config
import collections
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from rules.audits import BASE_FIRST_NAMES, NOT_A_FIRST_NAME        # noqa: E402
from rules.base import ROOT                                          # noqa: E402
from rules.compound import looks_like_person                         # noqa: E402

OUT = ROOT / "WIKIDATA_FIXES.md"
# Generic items used as 'named after' whose English label/description describe one notable tree although the Dutch label is the plain species word.
GENERIC_TARGETS = {
    "Q33036816": ("oak", [("Q12004", "Quercus (oak genus)"), ("Q165145", "Quercus robur (pedunculate oak)")]),
    "Q59779138": ("beech", [("Q25403", "Fagus (beech genus)"), ("Q146149", "Fagus sylvatica (common beech)")]),
}


def main():
    recs = json.loads((config.ENRICHED / "osm_etymology.json").read_text())
    fn = BASE_FIRST_NAMES - NOT_A_FIRST_NAME
    street_items = lambda r: ", ".join(f"[{q}](https://www.wikidata.org/wiki/{q})" for q in r["tags"].get("wikidata", []))
    L = ["# Wikidata fixes to make", "",
         "Failures on the Wikidata side (not OpenStreetMap; see `OSM_FIXES.md` for those), found while using the street items' *named after* (P138) statements as evidence.",
         "Generated by `python src/wikidata_fixes.py`. Each entry gives the street, its gemeente, the Wikidata item to edit, what is wrong and what would be more correct. Verify before editing.", ""]
    by_target = collections.defaultdict(list)
    for r in recs:
        if r["via"] != "wikidata P138":
            continue
        for i in r["items"]:
            if i["qid"] in GENERIC_TARGETS:
                by_target[i["qid"]].append((r, i))
    L += ["## 1. 'Named after' points at an item whose English label describes one notable tree", ""]
    for q, rows in by_target.items():
        word, better = GENERIC_TARGETS[q]
        lab, desc = rows[0][1]["label"], rows[0][1]["description"]
        L += [f"### Target [{q}](https://www.wikidata.org/wiki/{q}): \"{lab}\" ({desc}); {len(rows)} street items",
              f"- **What is wrong:** the street items below say *named after* \"{lab}\", an item whose English label and description describe a single notable {word} tree (its Dutch label is plain \"{ {'oak': 'eik', 'beech': 'beukenboom'}[word] }\"). A street called after *{word} trees in general* is not named after one notable tree.",
              f"- **More correct (choose one):** either (a) set P138 on each street item to the species/genus, {', '.join(f'[{b}](https://www.wikidata.org/wiki/{b}) {n}' for b, n in better)}; or (b) fix the item [{q}](https://www.wikidata.org/wiki/{q}) itself, so its English label/description say '{word}' rather than 'notable {word} tree' (one edit that repairs all of these at once; check the item's other uses first).",
              "- **Affected street items:**"]
        for r, _ in sorted(rows, key=lambda x: (x[0]["gemeente"], x[0]["street"])):
            L.append(f"  - **{r['street']}**, gemeente {r['gemeente']}: {street_items(r)}")
        L.append("")
    L += ["## 2. 'Named after' contradicts the street name", ""]
    n2 = 0
    for r in recs:
        if r["via"] != "wikidata P138":
            continue
        for i in r["items"]:
            if looks_like_person(r["street"], fn) and i.get("category") not in ("person", None) and i["qid"] != "Q26180":
                n2 += 1
                L += [f"### {r['street']}, gemeente {r['gemeente']}",
                      f"- **Wikidata item:** {street_items(r)}",
                      f"- **What is wrong:** *named after* is [{i['qid']}](https://www.wikidata.org/wiki/{i['qid']}) \"{i['label']}\" ({i['description']}); the street name looks like a person's name (first name + name), not a building or fortress.",
                      "- **More correct:** the person the street is named after. I cannot identify them from the name alone: check the municipality's street-name records (or the street's Wikipedia/heemkunde page) and set P138 to that person; if the street merely runs along the citadel, remove P138.", ""]
    if not n2:
        L.append("(none found)\n")
    OUT.write_text("\n".join(L) + "\n")
    print(f"wrote {config.rel(OUT)}: {sum(len(v) for v in by_target.values())} generic-tree items, {n2} contradicting statements")


if __name__ == "__main__":
    main()
